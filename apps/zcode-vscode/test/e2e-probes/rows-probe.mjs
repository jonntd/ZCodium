import { execSync } from "node:child_process";
import { ChannelClient, SocketProtocol, VSBuffer, Emitter } from "@zcode/rpc";
import { RemoteServiceAccess } from "@zcode/client";
const pid = execSync("pgrep -f 'entry-http.js' | head -1").toString().trim();
const line = execSync(`lsof -nP -iTCP -sTCP:LISTEN -a -p ${pid}`).toString();
const PORT = line.match(/127\.0\.0\.1:(\d+)/)[1];
const ws = new WebSocket(`ws://127.0.0.1:${PORT}/ws`);
const onData = new Emitter(); const onClose = new Emitter(); const onEnd = new Emitter();
ws.addEventListener("message", async (e) => { const raw = e.data; const buf = typeof raw === "string" ? Buffer.from(raw,"utf8") : (raw instanceof Blob ? Buffer.from(await raw.arrayBuffer()) : Buffer.from(raw)); onData.fire(VSBuffer.wrap(new Uint8Array(buf))); });
ws.addEventListener("close", () => { onClose.fire(); onEnd.fire(); });
ws.addEventListener("error", () => { onClose.fire(); onEnd.fire(); });
const protocol = new SocketProtocol({ onData: onData.event, onClose: onClose.event, onEnd: onEnd.event, write(b){ if (ws.readyState===1) ws.send(Buffer.from(b.buffer)); }, end(){ws.close();}, drain(){return Promise.resolve();}, dispose(){ws.close();} });
const client = new ChannelClient(protocol);
const accessor = await new Promise((res, rej) => { const t=setTimeout(()=>rej(new Error("init timeout")),15000); client.onDidInitialize(()=>{clearTimeout(t);res(new RemoteServiceAccess(client));}); });
await accessor.zcodeAgentService.helloConversationV4();
await accessor.zcodeAgentService.initializeConversationV4({ kind: "clientHello", protocolVersion: 3, clientId: "rows-probe", clientKind: "web", appVersion: "0.2.0", capabilities: { historyFirst: true } });
const sessionId = process.argv[2];
const page = await accessor.zcodeAgentService.conversationRowsRangeV4({ workspacePath: "/tmp/zcode-antigravity-test", sessionId, limit: 50 });
console.log("rows:", JSON.stringify(page).slice(0, 2500));
process.exit(0);
